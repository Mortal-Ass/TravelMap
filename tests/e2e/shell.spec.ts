import {test,expect} from '@playwright/test';
test('未登录页面、注册切换与移动布局',async({page})=>{
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'欢迎回来'})).toBeVisible();
 await page.getByRole('button',{name:'第一次来？创建账号'}).click();
 await expect(page.getByLabel('昵称')).toBeVisible();
 await page.getByRole('button',{name:'切换主题'}).click();
 await expect(page.locator('.app')).toHaveAttribute('data-theme','dark');
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
test('注册、创建旅行、刷新持久化及退出',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'第一次来？创建账号'}).click();
 await page.getByLabel('昵称').fill('浏览器验收');
 await page.getByLabel('邮箱').fill(`browser${Date.now()}@example.com`);
 await page.getByLabel('密码').fill('browser-test-password');
 await page.getByRole('button',{name:'注册并开始'}).click();
 await page.getByRole('button',{name:'＋ 创建旅行'}).click();
 await page.getByLabel('旅行名称').fill('东京三日');
 await page.getByLabel('目的地').fill('东京');
 await page.getByLabel('出发日期').fill('2027-01-01');
 await page.getByLabel('结束日期').fill('2027-01-03');
 await page.getByRole('button',{name:'创建旅行',exact:true}).click();
 await expect(page.locator('aside')).toContainText('东京三日');
 await page.reload();
 await page.getByRole('button').filter({hasText:'东京三日'}).click();
 await expect(page.getByLabel('目的地')).toHaveValue('东京');
 await page.getByLabel('旅行地点地图').click({position:{x:150,y:120}});
 await page.getByLabel('地点名称').fill('测试选点');
 await page.getByLabel('类别').selectOption('酒店');
 await page.getByRole('button',{name:'保存地点'}).click();
 await expect(page.locator('.place-pin')).toHaveCount(1);
 await page.getByLabel('筛选地点类型').selectOption('餐厅');
 await expect(page.locator('.place-pin')).toHaveCount(0);
 await expect(page.getByText('暂无匹配地点')).toBeVisible();
 await page.getByLabel('筛选地点类型').selectOption('酒店');
 await expect(page.locator('.place-pin')).toHaveCount(1);
 await page.getByRole('button',{name:'查看全图'}).click();
 await page.getByRole('button',{name:'宿 测试选点'}).click();
 await page.getByLabel('备注').fill('联动测试');
 await page.getByRole('button',{name:'保存地点'}).click();
 await expect(page.getByRole('status')).toContainText('地点已保存');
 await page.getByLabel('已保存地点').selectOption({label:'测试选点'});
 await page.getByRole('button',{name:'加入当天行程'}).click();
 const stop=page.locator('.places ol li');
 await expect(stop).toHaveCount(1);
 await stop.getByLabel('开始时间').fill('09:00');
 await expect(stop.getByLabel('开始时间')).toHaveValue('09:00');
 await page.getByRole('button',{name:'加入当天行程'}).click();
 await expect(stop).toHaveCount(2);
 await stop.first().getByText('下移').click();
 await expect(stop.last().getByLabel('开始时间')).toHaveValue('09:00');
 await stop.last().getByLabel('移动到日期').fill('2027-01-02');
 await expect(stop).toHaveCount(1);
 await page.getByLabel('行程日期').fill('2027-01-02');
 await expect(stop.first().getByLabel('开始时间')).toHaveValue('09:00');
 await page.getByText('攻略导入',{exact:true}).click();
 await page.getByLabel('读取 TXT 或 Markdown').setInputFiles({
  name:'攻略.md',mimeType:'text/markdown',buffer:Buffer.from('# 第二天\n- 12:00–13:00 测试选点')
 });
 await page.getByText('生成草稿',{exact:true}).click();
 const confirm=page.getByRole('button',{name:'确认导入 1 站'});
 await expect(confirm).toBeDisabled();
 await page.getByLabel('匹配已有地点').selectOption({label:'测试选点'});
 await expect(page.getByLabel('抵达')).toHaveValue('12:00');
 await confirm.click();
 await expect(page.getByText('已导入 1 站')).toBeVisible();
 await page.getByLabel('行程日期').fill('2027-01-02');
 await expect(page.getByLabel('开始时间').last()).toHaveValue('12:00');
 await page.context().grantPermissions(['geolocation']);
 await page.context().setGeolocation({latitude:41.8,longitude:123.4,accuracy:8});
 await page.getByText('成员位置共享',{exact:true}).click();
 await page.getByRole('button',{name:'开启位置共享'}).click();
 await expect(page.getByText(/精度约 8 米/)).toBeVisible({timeout:10000});
 await page.getByRole('button',{name:'停止位置共享'}).click();
 await expect(page.getByText(/精度约 8 米/)).toHaveCount(0);
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'展开每日行程'}).click();
 await expect(page.getByRole('button',{name:'收起每日行程'})).toHaveAttribute('aria-expanded','true');
 await page.getByText('安装与离线行程',{exact:true}).click();
 await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
 await page.getByText('保存到本机',{exact:true}).click();
 await expect(page.getByText('已保存本次行程的只读副本')).toBeVisible();
 await page.context().setOffline(true);
 await page.reload({waitUntil:'domcontentloaded'});
 await expect(page.getByRole('heading',{name:'离线行程'})).toBeVisible();
 await expect(page.getByRole('listitem').filter({hasText:'12:00'})).toContainText('测试选点');
 await page.context().setOffline(false);
 await expect(page.getByRole('heading',{name:/我的旅行/})).toBeVisible();
 await page.getByRole('button',{name:'退出',exact:true}).click();
 await expect.poll(()=>page.evaluate(()=>localStorage.getItem('travelmap.offline.agenda'))).toBeNull();
 await expect(page.getByRole('heading',{name:'欢迎回来'})).toBeVisible();
});
